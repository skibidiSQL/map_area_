// Задаем уникальные имена для локальных хранилищ (кэшей)
// 'C' — основной кэш для файлов приложения. При изменении версии старый кэш удалится
// 'PANO' — отдельный постоянный кэш только для тяжелых картинок-панорам
const C = 'tk-spacemap-v4', PANO = 'tk-spacemap-pano',
      // Массив SHELL: список базовых файлов приложения, необходимых для работы интерфейса (HTML, CSS, иконки, логика)
      SHELL = ['./', 'index.html', 'style.css', 'script.js', 'app.js', 'manifest.webmanifest', 'icon.svg'],
      // Массив VENDOR: список сторонних файлов (3D-движок и CSS-файл шрифтов)
      VENDOR = ['embed', 'vendor/three.min.js', 'vendor/fonts.css'];

// Обработчик события 'install'. Срабатывает один раз, когда браузер впервые скачивает и устанавливает этот сервис-воркер
self.addEventListener('install', e => e.waitUntil((async () => {
  // Открываем основной кэш приложения по его имени (tk-spacemap-v4)
  const c = await caches.open(C);
  // Проходимся по массивам SHELL и VENDOR и отправляем запросы на скачивание всех этих файлов, чтобы сохранить их в кэше
  await Promise.allSettled(SHELL.concat(VENDOR).map(u => c.add(u)));
  
  try { 
    // Хитрый трюк для шрифтов: читаем скачанный файл vendor/fonts.css как простой текст
    const css = await (await c.match('vendor/fonts.css')).text(), 
          // Определяем базовый URL для правильного вычисления путей к самим файлам шрифтов
          base = new URL('vendor/fonts.css', self.registration.scope);
    // Ищем в тексте CSS все конструкции 'url(...)' (где лежат ссылки на файлы .woff2), 
    // формируем для каждой абсолютную ссылку и тоже добавляем сам файл шрифта в кэш
    await Promise.allSettled([...css.matchAll(/url\(([^)]+)\)/g)].map(m => c.add(new URL(m[1].replace(/['"]/g, ''), base).href)));
  } catch {} // Если шрифты не скачались, просто игнорируем ошибку (приложение будет работать со стандартными шрифтами)
  
  // Принудительно заставляем этот сервис-воркер активироваться немедленно (не дожидаясь, пока пользователь закроет все вкладки со старой версией сайта)
  await self.skipWaiting();
})()));

// Обработчик события 'activate'. Срабатывает после установки, когда сервис-воркер готов брать на себя контроль над страницами
self.addEventListener('activate', e => e.waitUntil(
  // Берем список всех существующих в браузере кэшей для нашего сайта
  caches.keys()
    // Оставляем только те, имена которых не совпадают с текущими (C и PANO), то есть ищем устаревшие версии кэша, 
    // и безвозвратно удаляем их (caches.delete), чтобы освободить место на устройстве
    .then(k => Promise.all(k.filter(x => x != C && x != PANO).map(x => caches.delete(x))))
    // Заставляем новый сервис-воркер сразу взять под контроль все открытые вкладки нашего приложения
    .then(() => clients.claim())
));

// Обработчик события 'fetch'. Перехватывает АБСОЛЮТНО ВСЕ сетевые запросы, которые делает страница (картинки, скрипты, API)
self.addEventListener('fetch', e => {
  const r = e.request, u = new URL(r.url);
  // Если это не простой запрос на чтение (GET) — например, отправка данных POST, — мы его не трогаем и не кэшируем
  if (r.method != 'GET') return;

  // ОСОБЫЙ СЦЕНАРИЙ ДЛЯ ПАНОРАМ (Cache First):
  // Если браузер запрашивает файл из публичного бакета Supabase Storage (наши 360-панорамы)
  if (u.hostname.endsWith('.supabase.co') && u.pathname.includes('/storage/v1/object/public/')) {
    // Подменяем ответ браузеру нашей логикой
    e.respondWith(caches.open(PANO).then(async c => {
      // Ищем запрошенную панораму в постоянном кэше PANO
      const hit = await c.match(r);
      // Если она там есть, моментально возвращаем её (без обращения к интернету, экономим трафик и время)
      if (hit) return hit;
      
      // Если панорамы в кэше еще нет, скачиваем её из интернета
      const res = await fetch(r);
      // Если скачалась успешно (код 200), сохраняем точную копию (clone) в кэш PANO для будущих просмотров
      if (res.ok) c.put(r, res.clone());
      // Отдаем картинку для отображения на экране
      return res;
    }));
    return;
  }

  // Если это запрос на другой сайт (cross-origin) или обращение к какому-то динамическому /api, не вмешиваемся в него
  if (u.origin != location.origin || u.pathname.startsWith('/api')) return;

  // ОБЫЧНЫЙ СЦЕНАРИЙ ДЛЯ СТАТИКИ САЙТА (Network First с фолбеком на кэш):
  e.respondWith(
    // Сначала всегда пытаемся получить свежую версию файла (index.html, script.js) из интернета
    fetch(r).then(res => {
      // Если интернет есть и файл скачался успешно, обновляем его в нашем основном кэше C
      if (res.ok) { const k = res.clone(); caches.open(C).then(c => c.put(r, k)); }
      return res;
    // .catch сработает, если интернета нет (fetch выбросит ошибку сети)
    }).catch(async () => 
      // Если интернета нет, ищем запрашиваемый файл в нашем кэше C (игнорируя параметры после ? в URL)[
      (await caches.match(r, { ignoreSearch: true })) 
      // Если файла в кэше нет, но пользователь пытается открыть страницу сайта (mode == 'navigate'),
      // мы принудительно отдаем закэшированный index.html. Это нужно, чтобы ссылки вида /#/m/id/token работали в офлайне
      || (r.mode == 'navigate' ? caches.match('index.html') : Response.error())
    )
  );
});